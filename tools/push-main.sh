#!/usr/bin/env bash
# ==========================================================================
# ارسال کار صفحه آغاز به main — یک عملیات اتمی
# --------------------------------------------------------------------------
# چرا اتمی: در این محیط، متادیتای گیت (.git) بین اجراها چند بار به حالت
# قدیمی برگشته است. اگر fetch و commit و push در چند دستور جدا اجرا شوند،
# خطر این هست که وسط کار تاریخچه عقب برود و کامیت گم شود. پس همه‌چیز در یک
# اجرا انجام می‌گیرد.
#
# چرا به origin/main بازنشانی می‌شویم: کارهای پیشین (سایدبار، مایگریشن) روی
# گیت‌هاب نشسته‌اند ولی ممکن است در نسخه محلی نباشند. بازنشانی --mixed فقط
# اشاره‌گر و ایندکس را جلو می‌برد؛ هیچ فایلی از درخت کار حذف نمی‌شود. پس
# فایل‌های تازه سر جای خودشان می‌مانند و روی نسخه درست سوار می‌شوند.
#
# توکن:
#     هرگز در فایل نوشته نمی‌شود و در آدرس ریموت ذخیره نمی‌شود؛ فقط با
#     متغیر محیطی GH_TOKEN خوانده و در همان یک دستور push مصرف می‌شود.
#     توجه: اگر توکن را روی خط فرمان بنویسید، در تاریخچه پوسته می‌ماند.
#     راه امن‌تر:  read -rs GH_TOKEN && export GH_TOKEN
#
# اجرا:
#     GH_TOKEN=... bash tools/push-main.sh
# ==========================================================================
set -euo pipefail

REMOTE="https://github.com/fatemelakzaei75-blip/SolonBeauty.git"
BRANCH="main"

if [ -z "${GH_TOKEN:-}" ]; then
    echo "❌ متغیر GH_TOKEN تنظیم نشده است." >&2
    echo "   راه امن:  read -rs GH_TOKEN && export GH_TOKEN" >&2
    exit 1
fi

cd "$(dirname "$0")/.."

echo "▸ ۱) پاک‌سازی خروجی‌های ساخت (تا وارد کامیت نشوند)"
rm -rf BlazorAppSolon/bin BlazorAppSolon/obj \
       DataCore/bin DataCore/obj DataLayer/bin DataLayer/obj \
       WebApiSolon/bin WebApiSolon/obj 2>/dev/null || true
find . -name __pycache__ -type d -exec rm -rf {} + 2>/dev/null || true

echo "▸ ۲) تنظیم ریموت (بدون توکن در آدرس)"
if git remote get-url origin >/dev/null 2>&1; then
    git remote set-url origin "$REMOTE"
else
    git remote add origin "$REMOTE"
fi
git config user.name  "Arena Agent"
git config user.email "agent@arena.ai"

echo "▸ ۳) واکشی وضعیت واقعی گیت‌هاب"
git fetch origin "$BRANCH"

echo "▸ ۴) نشستن روی آخرین وضعیت گیت‌هاب (فایل‌های محلی دست‌نخورده می‌مانند)"
git reset --mixed "origin/$BRANCH"

echo "▸ ۵) فایل‌های تازه"
git add -A

if git diff --cached --quiet; then
    echo "   هیچ تغییر تازه‌ای برای کامیت نیست؛ فقط push انجام می‌شود."
else
    git commit -F - <<'MSG'
feat(splash): صفحه آغاز با نماد بی‌نهایت و بارگذاری واقعی — مرحله ۱ تا ۶

صفحه آغاز نرم‌افزار از صفر ساخته شد: نماد ∞ به‌عنوان مسیر SVG، نوار پیشرفت
که با «یک نور» پر می‌شود، متن و درصد فارسی، حالت خطا و محو شدن نرم پایانی.

معماری
- مارک‌آپ به‌صورت خواهرِ #app در index.html می‌نشیند، نه فرزندش. Blazor با
  نخستین رندر محتوای #app را دور می‌ریزد؛ هر خطایی در این انتخاب یعنی پرش
  دیده‌شدنی برای کاربر.
- هندسه مسیر فقط یک بار تعریف شده و سه لایه (مسیر خالی، هاله، خط پیشرفت)
  با use به همان ارجاع می‌دهند. pathLength="1" یعنی هیچ عدد جادویی طول مسیر
  در CSS نمی‌آید.
- رنگ‌ها فقط توکن‌اند و روی .s-splash دامنه دارند، نه :root؛ این فایل در همه
  صفحات بار می‌شود و نباید چیزی به بیرون درز بدهد.

پیشرفت واقعی، بدون تایمر تقلبی
- فاز اول (۰ تا ۴۵٪): پیشرفت واقعی دانلود خود Blazor از
  --blazor-load-percentage، با MutationObserver و بدون نظرسنجی دوره‌ای.
- فاز دوم (۴۵ تا ۱۰۰٪): پنج گام واقعی در BootService — نشست و توکن، تنظیمات
  سالن از API، لوگو، فونت وزیرمتن و تصویر هیرو. هر گام سقف زمانی دارد و کل
  فاز بودجه زمانی دارد.
- نگهبان یک‌نوا روی هر دو منبع: ایشوی شناخته‌شده aspnetcore مقدار را از ۱۰۰
  به ۹۸ برمی‌گرداند و بدون این محافظ، نوار عقب می‌رفت.
- خزیدن محدود: پس از ۲ ثانیه سکوت، نوار آرام به سقف فاز اول نزدیک می‌شود،
  ولی هرگز از آن رد نمی‌شود و هرگز به ۱۰۰ نمی‌رسد. ۱۰۰٪ تنها جای واقعی، پس
  از موفقیت هر پنج گام.
- نگهبان ۲۰ ثانیه‌ای در جاوااسکریپت: اگر خود Blazor بالا نیاید، هیچ کد
  سی‌شارپی وجود ندارد که خطا را گزارش کند.

تجربه کاربری
- هدایت هوشمند فقط از مسیر «/»: بازدیدکننده وارد‌شده مستقیم به پنل نقش خودش
  می‌رود؛ پیوندهای عمیق هرگز ربوده نمی‌شوند.
- حداقل ۸۰۰ میلی‌ثانیه نمایش تا صفحه چشمک نزند، بعد محو شدن نرم.
- خطا: نماد همان‌جا خشک می‌شود، پیام ساده فارسی و دکمه «تلاش دوباره» با
  هدف لمس ۴۴ پیکسل.
- قفل اسکرول پس‌زمینه تا پایان کار، و آزادسازی آن در پایان و در خطا.

موبایل و دسترس‌پذیری
- نماد ۹۰٪ عرض با سقف ۴۶۰ پیکسل: روی گوشی بزرگ و روی دسکتاپ وسط‌چین و
  در اندازه درست خودش. قاعده مخصوص صفحه‌های کوتاه برای گوشی افقی.
- safe-area با max(16px, env(...)) و viewport-fit=cover.
- role=status + aria-live=polite روی ردیف وضعیت؛ عدد دیده‌شدنی از درخت
  دسترس‌پذیری کنار گذاشته شده و اعلام‌ها فقط سر هر ۱۰ درصد می‌آید (۱۰ اعلام
  در ۱۰۰ پله، نه ۱۰۰ اعلام).
- احترام کامل به prefers-reduced-motion: انیمیشن تزئینی خاموش، ولی پیشرفت
  واقعی همچنان نمایش داده می‌شود.
- کنتراست همه متن‌ها بین ۶:۱ تا ۱۵:۱.

ابزارها
- tools/splash_markup.py منبع واحد مارک‌آپ، tools/sync-splash-markup.py
  همگام‌ساز با index.html، tools/build-splash-preview.py سازنده پیش‌نمایش.
- tools/test-splash.js با ۱۹۶ بررسی: هندسه مسیر، تقارن، مارک‌آپ، توکن‌های
  رنگ، کنتراست، واکنش‌گرایی، هر دو فاز پیشرفت، نگهبان یک‌نوا، خزیدن محدود،
  پایان، خطا و سیم‌کشی سی‌شارپ.

پاکسازی
- پنج قاعده مرده .loading-progress* از app.css حذف شد؛ لودر سبک قدیمی که
  داخل #app بود و با نخستین رندر ناپدید می‌شد، دیگر وجود ندارد.
- Authorizing روشن در App.razor خنثی شد تا پشت صفحه آغاز پرش رنگ نسازد.
MSG
fi

echo "▸ ۶) ارسال به گیت‌هاب"
# توکن فقط در همین یک دستور مصرف می‌شود و هیچ‌جا ذخیره نمی‌شود.
# sed خروجی را از توکن پاک می‌کند تا در گزارش‌ها لو نرود.
git push "https://x-access-token:${GH_TOKEN}@github.com/fatemelakzaei75-blip/SolonBeauty.git" \
    "HEAD:refs/heads/${BRANCH}" 2>&1 | sed "s/${GH_TOKEN}/[TOKEN-REDACTED]/g"

echo ""
echo "✅ انجام شد."
git log --oneline -3
