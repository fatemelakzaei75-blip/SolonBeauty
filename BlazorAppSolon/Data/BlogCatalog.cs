    public static BlogPost? BySlug(string slug)
        => Posts.FirstOrDefault(p => p.Slug.Equals(slug, StringComparison.OrdinalIgnoreCase));

    public static string[] Categories
        => Posts.Select(p => p.Category).Distinct().ToArray();

    public static List<BlogPost> Related(BlogPost post)
        => Posts.Where(p => p.Slug != post.Slug && p.Category == post.Category)
                .Concat(Posts.Where(p => p.Slug != post.Slug))
                .Distinct().Take(3).ToList();
}
